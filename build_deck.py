# ---------------- helpers ----------------
def rtl(p, algn='r'):
    pPr = p._p.get_or_add_pPr()
    pPr.set('rtl','1'); pPr.set('algn', algn)

def font(run, size=16, bold=False, color=TEXT, italic=False, name=FONT):
    run.font.size = Pt(size); run.font.bold = bold; run.font.italic = italic
    run.font.color.rgb = color
    rPr = run._r.get_or_add_rPr()
    for tag in ('latin','ea','cs'):
        el = rPr.find(qn('a:'+tag))
        if el is None:
            el = rPr.makeelement(qn('a:'+tag), {}); rPr.append(el)
        el.set('typeface', name)

def tb(slide, x, y, w, h, anchor='t'):
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = box.text_frame; tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = {'t':MSO_ANCHOR.TOP,'m':MSO_ANCHOR.MIDDLE,'b':MSO_ANCHOR.BOTTOM}[anchor]
    return box, tf

def para(tf, first=False):
    return tf.paragraphs[0] if first and not tf.paragraphs[0].runs else tf.add_paragraph()

def line(tf, text, size=16, bold=False, color=TEXT, algn='r', space_after=6,
         space_before=0, italic=False, first=False):
    p = para(tf, first)
    r = p.add_run(); r.text = text
    font(r, size, bold, color, italic)
    rtl(p, algn)
    p.space_after = Pt(space_after); p.space_before = Pt(space_before)
    return p

def pic(slide, name, x, y, w, h):
    path = A + name + '.jpg'
    im = Image.open(path)
    ia, ba = im.width/im.height, w/h
    p = slide.shapes.add_picture(path, Inches(x), Inches(y), Inches(w), Inches(h))
    if ia > ba:
        c = (1 - ba/ia)/2; p.crop_left = c; p.crop_right = c
    else:
        c = (1 - ia/ba)/2; p.crop_top = c; p.crop_bottom = c
    p.line.color.rgb = RGBColor(0xFF,0xFF,0xFF); p.line.width = Pt(2.75)
    return p

def rect(slide, x, y, w, h, fill=None, line_c=None, line_w=1.0, shape=MSO_SHAPE.RECTANGLE, radius=None, shadow=False):
    sp = slide.shapes.add_shape(shape, Inches(x), Inches(y), Inches(w), Inches(h))
    if fill is None:
        sp.fill.background()
    else:
        sp.fill.solid(); sp.fill.fore_color.rgb = fill
    if line_c is None:
        sp.line.fill.background()
    else:
        sp.line.color.rgb = line_c; sp.line.width = Pt(line_w)
    sp.shadow.inherit = False
    if radius is not None and shape == MSO_SHAPE.ROUNDED_RECTANGLE:
        try: sp.adjustments[0] = radius
        except Exception: pass
    return sp

def cap(slide, text, x, y, w, algn='r', color=GRAY, size=10.5):
    _, tf = tb(slide, x, y, w, 0.3)
    line(tf, text, size=size, color=color, algn=algn, space_after=0, first=True)

