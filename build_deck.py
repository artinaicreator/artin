# ---------------- timeline helper ----------------
def timeline(slide, items, y=3.55):
    n = len(items)
    x0, x1 = M+0.15, SW-M-0.15
    step = (x1-x0)/(n-1)
    rect(slide, x0, y, x1-x0, 0.03, fill=RGBColor(0xC7,0xD4,0xE2))
    for i,(yr, lbl, sub) in enumerate(items):
        cx = x0 + i*step
        dot = slide.shapes.add_shape(MSO_SHAPE.OVAL, Inches(cx-0.085), Inches(y-0.07), Inches(0.17), Inches(0.17))
        dot.fill.solid(); dot.fill.fore_color.rgb = BLUE if i%2==0 else NAVY2
        dot.line.color.rgb = WHITE; dot.line.width = Pt(1.5); dot.shadow.inherit = False
        bw = step*1.02
        bx = max(0.12, min(SW-bw-0.12, cx - bw/2))
        if i % 2 == 0:
            _, tf = tb(slide, bx, y-2.02, bw, 1.85)
            line(tf, yr, size=16, bold=True, color=BLUE, algn='c', space_after=2, first=True)
            line(tf, lbl, size=10.5, bold=True, color=NAVY2, algn='c', space_after=1)
            if sub: line(tf, sub, size=9, color=GRAY, algn='c', space_after=0)
            rect(slide, cx-0.012, y-0.16, 0.024, 0.12, fill=RGBColor(0xC7,0xD4,0xE2))
        else:
            rect(slide, cx-0.012, y+0.16, 0.024, 0.12, fill=RGBColor(0xC7,0xD4,0xE2))
            _, tf = tb(slide, bx, y+0.32, bw, 1.85)
            line(tf, yr, size=16, bold=True, color=NAVY2, algn='c', space_after=2, first=True)
            line(tf, lbl, size=10.5, bold=True, color=NAVY2, algn='c', space_after=1)
            if sub: line(tf, sub, size=9, color=GRAY, algn='c', space_after=0)

